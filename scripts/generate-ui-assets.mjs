import { mkdir, readFile, writeFile, copyFile, stat } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

// The browser receives only this subset, not lucide-static or an icon font.
const names = [
  'activity',
  'house',
  'shopping-bag',
  'package',
  'utensils',
  'sparkles',
  'chart-no-axes-combined',
  'settings-2',
  'qr-code',
  'users-round',
  'arrow-up-right',
  'arrow-left',
  'arrow-up',
  'arrow-down',
  'plus',
  'minus',
  'search',
  'log-out',
  'user-round',
  'pencil',
  'download',
  'x',
  'save',
  'circle-check',
  'chef-hat',
  'check-check',
  'banknote',
  'refresh-cw',
  'circle-alert',
  'send',
  'calendar-days',
  'music',
  'mic-vocal',
  'tv',
  'map-pin',
  'panel-left-open',
  'panel-left-close',
];
const root = new URL('../', import.meta.url);
const icons = new URL('public/icons/', root);
const fonts = new URL('public/fonts/', root);
await mkdir(icons, { recursive: true });
await mkdir(fonts, { recursive: true });
const symbols = await Promise.all(
  names.map(async (name) => {
    const svg = await readFile(
      new URL(`node_modules/lucide-static/icons/${name}.svg`, root),
      'utf8',
    );
    const body = svg
      .match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)[1]
      .trim()
      .replace(/\s+/g, ' ');
    return `<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`;
  }),
);
const sprite = `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide; see LICENSE.txt -->${symbols.join('')}</svg>\n`;
await writeFile(new URL('ui.svg', icons), sprite);
await copyFile(new URL('node_modules/lucide-static/LICENSE', root), new URL('LICENSE.txt', icons));
await writeFile(
  new URL('src/app/icon-names.ts', root),
  `// Generated by npm run assets:ui.\nexport type IconName = ${names.map((name) => `'${name}'`).join(' | ')};\n`,
);
for (const font of ['bricolage-grotesque', 'space-grotesk']) {
  await copyFile(
    new URL(
      `node_modules/@fontsource-variable/${font}/files/${font}-latin-wght-normal.woff2`,
      root,
    ),
    new URL(`${font}-latin.woff2`, fonts),
  );
  await copyFile(
    new URL(`node_modules/@fontsource-variable/${font}/LICENSE`, root),
    new URL(`${font}-LICENSE.txt`, fonts),
  );
}
const size = await stat(new URL('ui.svg', icons));
console.log(
  `${names.length} SVG icons: ${size.size} bytes; ${gzipSync(sprite).length} bytes gzip. Fonts: Latin variable WOFF2 only.`,
);
